from pathlib import Path

import pandas as pd


# =========================================================
# 1. 경로 설정
# =========================================================

BASE_DIR = Path(__file__).resolve().parent.parent

INPUT_FILE = (
    BASE_DIR
    / "data"
    / "processed"
    / "25개동_통합분석.csv"
)

OUTPUT_FILE = (
    BASE_DIR
    / "data"
    / "processed"
    / "청년주거환경_정책검토지역.csv"
)


# =========================================================
# 2. 취약요인별 정책 검토 방향
# =========================================================

POLICY_GUIDE = {

    "생활인프라점수":
        "생활SOC·의료·편의·문화시설 확충 필요성 검토",

    "2030선호시설점수":
        "청년 문화·운동·생활편의시설 확충 필요성 검토",

    "교통접근성점수":
        "버스정류장 및 대중교통 접근성 개선 필요성 검토",

    "주거가성비점수":
        "청년 주거비 지원·공공임대·부담 가능한 주택 공급 필요성 검토",
}


# =========================================================
# 3. Boolean 안전 변환
# =========================================================

def to_bool(value):

    if isinstance(value, bool):
        return value

    text = str(value).strip().lower()

    return text in [
        "true",
        "1",
        "yes",
        "y"
    ]


# =========================================================
# 4. 취약유형 이름 만들기
# =========================================================

def make_weak_type(weak_factors):

    short_names = {

        "생활인프라": "생활",

        "2030선호시설": "청년시설",

        "교통접근성": "교통",

        "주거가성비": "주거",
    }


    if len(weak_factors) >= 3:

        return "복합 취약형"


    if len(weak_factors) == 2:

        first = short_names.get(
            weak_factors[0],
            weak_factors[0]
        )

        second = short_names.get(
            weak_factors[1],
            weak_factors[1]
        )

        return f"{first}·{second} 취약형"


    if len(weak_factors) == 1:

        name = short_names.get(
            weak_factors[0],
            weak_factors[0]
        )

        return f"{name} 취약형"


    # 예전처럼 억지로 가장 낮은 항목을
    # 취약요인으로 지정하지 않음
    return "뚜렷한 취약요인 없음"


# =========================================================
# 5. 주거 데이터 주의사항
# =========================================================

def make_housing_note(row):

    status = str(
        row.get(
            "주거표본판정",
            ""
        )
    ).strip()


    if status == "표본부족":

        return (
            "주거 거래 5건 미만으로 "
            "주거가성비점수 미사용·정책순위 비교 제외"
        )


    if status == "저표본 주의":

        return (
            "주거 거래 5~19건으로 "
            "주거비 해석 시 주의 필요"
        )


    return ""


# =========================================================
# 6. 정책 분석
# =========================================================

def analyze_policy():

    print()
    print(
        "========================================"
    )

    print(
        "청년 주거환경 정책 분석 시작"
    )

    print(
        "========================================"
    )


    # =====================================================
    # 파일 확인
    # =====================================================

    if not INPUT_FILE.exists():

        print(
            "\n통합분석 파일이 없습니다."
        )

        print(
            INPUT_FILE
        )

        return


    # =====================================================
    # 데이터 읽기
    # =====================================================

    df = pd.read_csv(
        INPUT_FILE,
        encoding="utf-8-sig"
    )


    if df.empty:

        print(
            "분석할 데이터가 없습니다."
        )

        return


    print(
        f"\n전체 분석지역 : "
        f"{len(df)}개"
    )


    # =====================================================
    # 필수 컬럼 검사
    # =====================================================

    required_columns = [

        "자치구",
        "행정동",

        "HL_Score",

        "생활인프라점수",
        "2030선호시설점수",
        "교통접근성점수",
        "주거가성비점수",

        "월환산주거비_평균값_만원",

        "주거표본판정",
        "HL산출유형",
        "HL비교가능성",

        "정책순위포함여부"
    ]


    missing_columns = [

        column

        for column in required_columns

        if column not in df.columns
    ]


    if missing_columns:

        print()
        print(
            "필수 컬럼이 없습니다."
        )

        for column in missing_columns:

            print(
                "-",
                column
            )

        return


    # =====================================================
    # 지역명
    # =====================================================

    if "지역" not in df.columns:

        df[
            "지역"
        ] = (

            df[
                "자치구"
            ].astype(str)

            + " "

            + df[
                "행정동"
            ].astype(str)

        )


    # =====================================================
    # 정책순위 포함 여부 Boolean 변환
    # =====================================================

    df[
        "정책순위포함여부"
    ] = (

        df[
            "정책순위포함여부"
        ]

        .apply(
            to_bool
        )

    )


    # =====================================================
    # 기존 후속 스크립트 호환용
    #
    # 이름은 월환산주거비지만
    # 실제 값은 새 평균값을 사용
    # =====================================================

    df[
        "월환산주거비"
    ] = df[
        "월환산주거비_평균값_만원"
    ]


    # =====================================================
    # 점수 컬럼
    # =====================================================

    score_columns = [

        "생활인프라점수",

        "2030선호시설점수",

        "교통접근성점수",

        "주거가성비점수",
    ]


    # =====================================================
    # 정책순위 비교 가능한 지역만 별도 추출
    #
    # 두암2동은 여기에서 제외
    # =====================================================

    comparison_df = df[
        df[
            "정책순위포함여부"
        ]
        == True
    ].copy()


    print(
        f"정책순위 비교 가능 : "
        f"{len(comparison_df)}개"
    )


    print(
        f"정책순위 비교 제외 : "
        f"{len(df) - len(comparison_df)}개"
    )


    # =====================================================
    # 각 지표 하위 25% 기준
    #
    # 정책순위 비교 가능한 지역을 기준으로 계산
    # =====================================================

    thresholds = {}


    for column in score_columns:

        valid_values = pd.to_numeric(
            comparison_df[
                column
            ],
            errors="coerce"
        ).dropna()


        if len(valid_values) == 0:

            thresholds[
                column
            ] = None

        else:

            thresholds[
                column
            ] = valid_values.quantile(
                0.25
            )


    # =====================================================
    # 정책 검토 등급
    # =====================================================

    result = df.copy()


    result[
        "정책검토등급"
    ] = "일반 관찰"


    # =====================================================
    # 두암2동 등 비교 불가능 지역
    # =====================================================

    result.loc[
        result[
            "정책순위포함여부"
        ]
        == False,
        "정책검토등급"
    ] = "정책순위 제외"


    # =====================================================
    # 비교 가능한 지역을 HL 낮은 순으로 정렬
    # =====================================================

    ranked = (

        result[
            result[
                "정책순위포함여부"
            ]
            == True
        ]

        .sort_values(
            by="HL_Score",
            ascending=True
        )

    )


    # =====================================================
    # 하위 5개
    #
    # 프로젝트 내부 정책검토 기준
    # =====================================================

    bottom5_index = (
        ranked
        .head(5)
        .index
    )


    result.loc[
        bottom5_index,
        "정책검토등급"
    ] = "우선 개선 검토"


    # =====================================================
    # 그 다음 5개
    # =====================================================

    next5_index = (
        ranked
        .iloc[5:10]
        .index
    )


    result.loc[
        next5_index,
        "정책검토등급"
    ] = "관심 검토"


    # =====================================================
    # 취약요인 분석
    # =====================================================

    weak_factors_list = []

    weak_type_list = []

    weak_count_list = []

    policy_list = []

    data_note_list = []


    for _, row in result.iterrows():

        weak_factors = []

        policies = []


        for column in score_columns:

            threshold = thresholds.get(
                column
            )


            value = pd.to_numeric(
                pd.Series(
                    [
                        row[
                            column
                        ]
                    ]
                ),
                errors="coerce"
            ).iloc[0]


            # =============================================
            # NaN 값은 취약요인 판단에서 제외
            #
            # 두암2동 주거가성비점수 등이 해당
            # =============================================

            if pd.isna(value):

                continue


            if threshold is None:

                continue


            # =============================================
            # 실제 하위 25%일 때만 취약요인
            # =============================================

            if value <= threshold:

                factor_name = (
                    column
                    .replace(
                        "점수",
                        ""
                    )
                )


                weak_factors.append(
                    factor_name
                )


                policies.append(
                    POLICY_GUIDE[
                        column
                    ]
                )


        # =================================================
        # 취약요인이 없다고 해서
        # 억지로 하나를 지정하지 않음
        # =================================================

        if not weak_factors:

            policy_text = (
                "상대적 하위 25%에 해당하는 "
                "뚜렷한 취약요인 없음"
            )

        else:

            policy_text = (
                " / ".join(
                    policies
                )
            )


        # =================================================
        # 취약유형
        # =================================================

        weak_type = make_weak_type(
            weak_factors
        )


        # =================================================
        # 주거 데이터 주의사항
        # =================================================

        data_note = make_housing_note(
            row
        )


        # =================================================
        # 정책순위 제외지역 안내 추가
        # =================================================

        if (
            row[
                "정책순위포함여부"
            ]
            == False
        ):

            if data_note:

                data_note += (
                    " / HL-Score는 참고용 접근성지수 기반"
                )

            else:

                data_note = (
                    "정책순위 비교 제외"
                )


        weak_factors_list.append(
            ", ".join(
                weak_factors
            )
            if weak_factors
            else "없음"
        )


        weak_type_list.append(
            weak_type
        )


        weak_count_list.append(
            len(
                weak_factors
            )
        )


        policy_list.append(
            policy_text
        )


        data_note_list.append(
            data_note
        )


    # =====================================================
    # 분석 결과 컬럼
    # =====================================================

    result[
        "주요취약요인"
    ] = weak_factors_list


    result[
        "취약유형"
    ] = weak_type_list


    result[
        "취약요인수"
    ] = weak_count_list


    result[
        "정책검토방향"
    ] = policy_list


    result[
        "데이터주의사항"
    ] = data_note_list


    # =====================================================
    # 정책검토 순서
    # =====================================================

    grade_order = {

        "우선 개선 검토": 1,

        "관심 검토": 2,

        "일반 관찰": 3,

        "정책순위 제외": 4
    }


    result[
        "_정책정렬"
    ] = (

        result[
            "정책검토등급"
        ]

        .map(
            grade_order
        )

    )


    result = (

        result

        .sort_values(
            by=[
                "_정책정렬",
                "HL_Score"
            ],
            ascending=[
                True,
                True
            ]
        )

        .drop(
            columns=[
                "_정책정렬"
            ]
        )

    )


    # =====================================================
    # 최종 저장 컬럼
    # =====================================================

    final_columns = [

        "자치구",
        "행정동",
        "지역",

        "HL_Score",

        "HL정책비교순위",

        # 기존 후속 코드 호환
        "월환산주거비",

        # 실제 새 주거비 컬럼
        "월환산주거비_평균값_만원",

        "전체거래건수",

        "생활인프라점수",
        "2030선호시설점수",
        "교통접근성점수",
        "주거가성비점수",

        "정책검토등급",

        "취약유형",
        "취약요인수",
        "주요취약요인",

        "정책검토방향",

        "주거표본판정",
        "HL산출유형",
        "HL비교가능성",
        "정책순위포함여부",

        "데이터주의사항",
    ]


    # HL정책비교순위가 없는 경우 대비
    final_columns = [

        column

        for column in final_columns

        if column in result.columns

    ]


    final_df = result[
        final_columns
    ].copy()


    # =====================================================
    # CSV 저장
    # =====================================================

    final_df.to_csv(
        OUTPUT_FILE,
        index=False,
        encoding="utf-8-sig"
    )


    # =====================================================
    # 결과 출력
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "청년 주거환경 정책 분석 완료"
    )

    print(
        "========================================"
    )


    # =====================================================
    # 우선 개선
    # =====================================================

    print()
    print(
        "[우선 개선 검토지역]"
    )


    priority = final_df[
        final_df[
            "정책검토등급"
        ]
        == "우선 개선 검토"
    ]


    for _, row in priority.iterrows():

        print()
        print(
            "----------------------------------------"
        )

        print(
            f"지역 : "
            f"{row['지역']}"
        )

        print(
            f"HL-Score : "
            f"{row['HL_Score']:.1f}"
        )

        print(
            f"취약유형 : "
            f"{row['취약유형']}"
        )

        print(
            f"주요 취약요인 : "
            f"{row['주요취약요인']}"
        )

        print(
            f"정책 검토 방향 : "
            f"{row['정책검토방향']}"
        )


        if (
            str(
                row.get(
                    "데이터주의사항",
                    ""
                )
            ).strip()
        ):

            print(
                f"데이터 주의 : "
                f"{row['데이터주의사항']}"
            )


    # =====================================================
    # 관심 검토
    # =====================================================

    print()
    print(
        "[관심 검토지역]"
    )


    interest = final_df[
        final_df[
            "정책검토등급"
        ]
        == "관심 검토"
    ]


    for _, row in interest.iterrows():

        print()
        print(
            "----------------------------------------"
        )

        print(
            f"지역 : "
            f"{row['지역']}"
        )

        print(
            f"HL-Score : "
            f"{row['HL_Score']:.1f}"
        )

        print(
            f"취약유형 : "
            f"{row['취약유형']}"
        )

        print(
            f"주요 취약요인 : "
            f"{row['주요취약요인']}"
        )


        if (
            str(
                row.get(
                    "데이터주의사항",
                    ""
                )
            ).strip()
        ):

            print(
                f"데이터 주의 : "
                f"{row['데이터주의사항']}"
            )


    # =====================================================
    # 정책순위 제외
    # =====================================================

    print()
    print(
        "[정책순위 비교 제외지역]"
    )


    excluded = final_df[
        final_df[
            "정책검토등급"
        ]
        == "정책순위 제외"
    ]


    if excluded.empty:

        print(
            "없음"
        )


    else:

        for _, row in excluded.iterrows():

            print()
            print(
                "----------------------------------------"
            )

            print(
                f"지역 : "
                f"{row['지역']}"
            )

            print(
                f"참고 HL-Score : "
                f"{row['HL_Score']:.1f}"
            )

            print(
                f"사유 : "
                f"{row['데이터주의사항']}"
            )


    # =====================================================
    # 최종 요약
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "정책분석 요약"
    )

    print(
        "========================================"
    )


    print(
        "우선 개선 검토 :",
        (
            final_df[
                "정책검토등급"
            ]
            == "우선 개선 검토"
        ).sum(),
        "개"
    )


    print(
        "관심 검토 :",
        (
            final_df[
                "정책검토등급"
            ]
            == "관심 검토"
        ).sum(),
        "개"
    )


    print(
        "일반 관찰 :",
        (
            final_df[
                "정책검토등급"
            ]
            == "일반 관찰"
        ).sum(),
        "개"
    )


    print(
        "정책순위 제외 :",
        (
            final_df[
                "정책검토등급"
            ]
            == "정책순위 제외"
        ).sum(),
        "개"
    )


    print()
    print(
        "※ 우선/관심 검토 구분은 "
        "프로젝트 내부 상대비교 기준입니다."
    )

    print(
        "※ 정책순위는 주거비 표본이 "
        "5건 이상인 지역만 비교합니다."
    )

    print(
        "※ 저표본 지역은 실제 값은 사용하되 "
        "정책 해석 시 주의합니다."
    )


    print()
    print(
        "----------------------------------------"
    )

    print(
        "저장 완료"
    )

    print(
        OUTPUT_FILE
    )

    print(
        "----------------------------------------"
    )


# =========================================================
# 실행
# =========================================================

if __name__ == "__main__":

    analyze_policy()