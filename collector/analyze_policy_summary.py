from pathlib import Path

import pandas as pd


# =========================================================
# 1. 파일 경로
# =========================================================

BASE_DIR = Path(__file__).resolve().parent.parent

INPUT_PATH = (
    BASE_DIR
    / "data"
    / "processed"
    / "청년주거환경_정책검토지역.csv"
)

OUTPUT_PATH = (
    BASE_DIR
    / "data"
    / "processed"
    / "청년주거환경_정책요약.csv"
)


# =========================================================
# 2. 정책 요약 분석
# =========================================================

def analyze_policy_summary():

    print()
    print(
        "========================================"
    )

    print(
        "청년 주거환경 정책 요약 분석 시작"
    )

    print(
        "========================================"
    )


    # =====================================================
    # 입력 파일 확인
    # =====================================================

    if not INPUT_PATH.exists():

        print(
            "\n입력 파일이 없습니다."
        )

        print(
            INPUT_PATH
        )

        return


    # =====================================================
    # 정책분석 결과 읽기
    # =====================================================

    df = pd.read_csv(
        INPUT_PATH,
        encoding="utf-8-sig"
    )


    if df.empty:

        print(
            "분석할 데이터가 없습니다."
        )

        return


    print(
        f"\n전체 분석지역 : "
        f"{len(df)}개"
    )


    # =====================================================
    # 필수 컬럼 검사
    # =====================================================

    required_columns = [

        "지역",
        "정책검토등급",
        "주요취약요인",
        "취약유형",

        "주거표본판정",
        "정책순위포함여부"
    ]


    missing_columns = [

        column

        for column in required_columns

        if column not in df.columns
    ]


    if missing_columns:

        print()
        print(
            "필수 컬럼이 없습니다."
        )

        for column in missing_columns:

            print(
                "-",
                column
            )

        return


    # =====================================================
    # 우선 + 관심 검토지역
    # =====================================================

    target_df = df[
        df[
            "정책검토등급"
        ].isin(
            [
                "우선 개선 검토",
                "관심 검토"
            ]
        )
    ].copy()


    # =====================================================
    # 정책순위 제외지역
    # =====================================================

    excluded_df = df[
        df[
            "정책검토등급"
        ]
        == "정책순위 제외"
    ].copy()


    # =====================================================
    # 취약요인 이름
    # =====================================================

    factors = {

        "생활 인프라":
            "생활인프라",

        "청년 선호시설":
            "2030선호시설",

        "교통 접근성":
            "교통접근성",

        "주거 가성비":
            "주거가성비",
    }


    summary_rows = []


    # =====================================================
    # 3. 정책검토등급 요약
    # =====================================================

    grade_order = [

        "우선 개선 검토",
        "관심 검토",
        "일반 관찰",
        "정책순위 제외"
    ]


    for grade in grade_order:

        temp = df[
            df[
                "정책검토등급"
            ]
            == grade
        ]


        summary_rows.append(

            {

                "구분":
                    "정책검토등급",

                "항목":
                    grade,

                "지역수":
                    len(temp),

                "대상지역":
                    ", ".join(
                        temp[
                            "지역"
                        ].tolist()
                    ),

                "비고":
                    ""
            }

        )


    # =====================================================
    # 4. 취약요인별 요약
    #
    # 우선 + 관심 검토지역만 분석
    # =====================================================

    for display_name, keyword in (
        factors.items()
    ):

        temp = target_df[
            target_df[
                "주요취약요인"
            ]
            .astype(str)
            .str.contains(
                keyword,
                na=False
            )
        ]


        summary_rows.append(

            {

                "구분":
                    "취약요인",

                "항목":
                    display_name,

                "지역수":
                    len(temp),

                "대상지역":
                    ", ".join(
                        temp[
                            "지역"
                        ].tolist()
                    ),

                "비고":
                    "우선 개선·관심 검토지역 기준"
            }

        )


    # =====================================================
    # 5. 뚜렷한 취약요인이 없는 지역
    # =====================================================

    no_weak = target_df[
        target_df[
            "주요취약요인"
        ]
        .astype(str)
        .eq(
            "없음"
        )
    ]


    summary_rows.append(

        {

            "구분":
                "취약요인",

            "항목":
                "뚜렷한 취약요인 없음",

            "지역수":
                len(no_weak),

            "대상지역":
                ", ".join(
                    no_weak[
                        "지역"
                    ].tolist()
                ),

            "비고":
                "상대적 하위 25% 지표 없음"
        }

    )


    # =====================================================
    # 6. 취약유형별 요약
    # =====================================================

    type_counts = (

        target_df[
            "취약유형"
        ]

        .value_counts()

    )


    for weak_type, count in (
        type_counts.items()
    ):

        temp = target_df[
            target_df[
                "취약유형"
            ]
            == weak_type
        ]


        summary_rows.append(

            {

                "구분":
                    "취약유형",

                "항목":
                    weak_type,

                "지역수":
                    int(
                        count
                    ),

                "대상지역":
                    ", ".join(
                        temp[
                            "지역"
                        ].tolist()
                    ),

                "비고":
                    "우선 개선·관심 검토지역 기준"
            }

        )


    # =====================================================
    # 7. 주거 표본 품질 요약
    # =====================================================

    sample_order = [

        "정상",
        "저표본 주의",
        "표본부족"
    ]


    for sample_status in sample_order:

        temp = df[
            df[
                "주거표본판정"
            ]
            == sample_status
        ]


        if sample_status == "정상":

            note = (
                "주거 거래 20건 이상"
            )


        elif sample_status == "저표본 주의":

            note = (
                "주거 거래 5~19건, "
                "정책 해석 시 주의"
            )


        else:

            note = (
                "주거 거래 5건 미만, "
                "주거점수 및 정책순위 비교 제외"
            )


        summary_rows.append(

            {

                "구분":
                    "주거표본",

                "항목":
                    sample_status,

                "지역수":
                    len(temp),

                "대상지역":
                    ", ".join(
                        temp[
                            "지역"
                        ].tolist()
                    ),

                "비고":
                    note
            }

        )


    # =====================================================
    # 8. 정책검토지역 중 저표본 지역
    # =====================================================

    low_target = target_df[
        target_df[
            "주거표본판정"
        ]
        == "저표본 주의"
    ]


    summary_rows.append(

        {

            "구분":
                "데이터주의",

            "항목":
                "정책검토지역 중 저표본",

            "지역수":
                len(low_target),

            "대상지역":
                ", ".join(
                    low_target[
                        "지역"
                    ].tolist()
                ),

            "비고":
                "HL-Score에는 반영되지만 "
                "주거비 해석 시 주의 필요"
        }

    )


    # =====================================================
    # 9. 정책순위 제외지역
    # =====================================================

    summary_rows.append(

        {

            "구분":
                "데이터주의",

            "항목":
                "정책순위 비교 제외",

            "지역수":
                len(excluded_df),

            "대상지역":
                ", ".join(
                    excluded_df[
                        "지역"
                    ].tolist()
                ),

            "비고":
                "주거 표본부족으로 "
                "동일 조건 정책순위 비교 제외"
        }

    )


    # =====================================================
    # 10. DataFrame 생성
    # =====================================================

    summary_df = pd.DataFrame(
        summary_rows
    )


    # =====================================================
    # 11. CSV 저장
    # =====================================================

    summary_df.to_csv(
        OUTPUT_PATH,
        index=False,
        encoding="utf-8-sig"
    )


    # =====================================================
    # 12. 터미널 출력
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "청년 주거환경 정책 요약 분석"
    )

    print(
        "========================================"
    )


    # =====================================================
    # 정책 검토지역
    # =====================================================

    print()
    print(
        "[정책 검토지역]"
    )


    for grade in grade_order:

        temp = df[
            df[
                "정책검토등급"
            ]
            == grade
        ]

        print(
            f"{grade} : "
            f"{len(temp)}개 지역"
        )


    # =====================================================
    # 주요 취약요인
    # =====================================================

    print()
    print(
        "[주요 취약요인]"
    )


    factor_summary = (

        summary_df[
            summary_df[
                "구분"
            ]
            == "취약요인"
        ]

        .sort_values(
            "지역수",
            ascending=False
        )

    )


    for _, row in (
        factor_summary.iterrows()
    ):

        print()

        print(
            f"{row['항목']} : "
            f"{row['지역수']}개 지역"
        )

        if str(
            row[
                "대상지역"
            ]
        ).strip():

            print(
                f"→ "
                f"{row['대상지역']}"
            )


    # =====================================================
    # 취약유형
    # =====================================================

    print()
    print(
        "[취약유형]"
    )


    type_summary = summary_df[
        summary_df[
            "구분"
        ]
        == "취약유형"
    ]


    for _, row in (
        type_summary.iterrows()
    ):

        print()

        print(
            f"{row['항목']} : "
            f"{row['지역수']}개 지역"
        )

        print(
            f"→ "
            f"{row['대상지역']}"
        )


    # =====================================================
    # 주거 데이터 품질
    # =====================================================

    print()
    print(
        "[주거 데이터 품질]"
    )


    sample_summary = summary_df[
        summary_df[
            "구분"
        ]
        == "주거표본"
    ]


    for _, row in (
        sample_summary.iterrows()
    ):

        print()

        print(
            f"{row['항목']} : "
            f"{row['지역수']}개 지역"
        )

        if str(
            row[
                "대상지역"
            ]
        ).strip():

            print(
                f"→ "
                f"{row['대상지역']}"
            )


    # =====================================================
    # 정책순위 제외
    # =====================================================

    print()
    print(
        "[정책순위 비교 제외]"
    )


    if excluded_df.empty:

        print(
            "없음"
        )


    else:

        for _, row in (
            excluded_df.iterrows()
        ):

            print(
                f"- "
                f"{row['지역']}"
            )


    # =====================================================
    # 최종 안내
    # =====================================================

    print()
    print(
        "----------------------------------------"
    )

    print(
        "저장 완료"
    )

    print(
        OUTPUT_PATH
    )

    print(
        "----------------------------------------"
    )


# =========================================================
# 실행
# =========================================================

if __name__ == "__main__":

    analyze_policy_summary()