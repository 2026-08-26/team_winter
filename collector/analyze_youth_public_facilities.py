from pathlib import Path

import pandas as pd


# =========================================================
# 1. 경로 설정
# =========================================================

BASE_DIR = Path(__file__).resolve().parent.parent

PROCESSED_DIR = (
    BASE_DIR
    / "data"
    / "processed"
)

FACILITY_FILE = (
    PROCESSED_DIR
    / "동별_청년공공시설.csv"
)

POPULATION_FILE = (
    PROCESSED_DIR
    / "동별_2030인구.csv"
)

OUTPUT_FILE = (
    PROCESSED_DIR
    / "2030_청년인구_대비_공공시설_분석.csv"
)


# =========================================================
# 2. 숫자 변환
# =========================================================

def to_numeric(series):

    return pd.to_numeric(
        series.astype(str)
        .str.replace(
            ",",
            "",
            regex=False
        ),
        errors="coerce"
    )


# =========================================================
# 3. 2030 인구수 컬럼 찾기
# =========================================================

def find_population_column(df):

    candidates = [

        "2030인구수",
        "2030_인구수",
        "2030인구",
        "청년인구수",
        "청년인구"
    ]


    for column in candidates:

        if column in df.columns:

            return column


    return None


# =========================================================
# 4. 지역 컬럼 만들기
# =========================================================

def make_region_column(df):

    result = df.copy()

    # 컬럼명 앞뒤 공백 제거
    result.columns = [
        str(column).strip()
        for column in result.columns
    ]


    # 이미 지역 컬럼이 있으면 그대로 사용
    if "지역" in result.columns:

        result["지역"] = (
            result["지역"]
            .astype(str)
            .str.strip()
        )

        return result


    # =====================================================
    # 1순위
    # 프로젝트에서 사용하는 자치구 표기
    #
    # 첨단2동:
    # 공식 = 광산구
    # 프로젝트 = 북구
    # =====================================================

    if (
        "팀계획_자치구" in result.columns
        and
        "행정동" in result.columns
    ):

        result["지역"] = (

            result["팀계획_자치구"]
            .astype(str)
            .str.strip()

            + " "

            + result["행정동"]
            .astype(str)
            .str.strip()
        )

        return result


    # =====================================================
    # 2순위
    # 일반 자치구 + 행정동
    # =====================================================

    if (
        "자치구" in result.columns
        and
        "행정동" in result.columns
    ):

        result["지역"] = (

            result["자치구"]
            .astype(str)
            .str.strip()

            + " "

            + result["행정동"]
            .astype(str)
            .str.strip()
        )

        return result


    # =====================================================
    # 3순위
    # 원본 공식 자치구
    # =====================================================

    if (
        "원데이터_자치구" in result.columns
        and
        "행정동" in result.columns
    ):

        result["지역"] = (

            result["원데이터_자치구"]
            .astype(str)
            .str.strip()

            + " "

            + result["행정동"]
            .astype(str)
            .str.strip()
        )

        return result


    print()
    print("현재 실제 컬럼명:")

    for column in result.columns:
        print("-", repr(column))


    raise ValueError(
        "지역 컬럼을 만들 수 없습니다."
    )


# =========================================================
# 5. 메인
# =========================================================

def main():

    print()
    print(
        "========================================"
    )

    print(
        "2030 청년인구 대비 공공시설 분석"
    )

    print(
        "========================================"
    )


    # =====================================================
    # 파일 확인
    # =====================================================

    if not FACILITY_FILE.exists():

        print()
        print(
            "청년 공공시설 파일이 없습니다."
        )

        print(
            FACILITY_FILE
        )

        return


    if not POPULATION_FILE.exists():

        print()
        print(
            "2030 청년인구 파일이 없습니다."
        )

        print(
            POPULATION_FILE
        )

        return


    # =====================================================
    # 파일 읽기
    # =====================================================

    facility_df = pd.read_csv(
        FACILITY_FILE,
        encoding="utf-8-sig"
    )

    population_df = pd.read_csv(
        POPULATION_FILE,
        encoding="utf-8-sig"
    )


    facility_df = make_region_column(
        facility_df
    )

    population_df = make_region_column(
        population_df
    )


    print()
    print(
        f"공공시설 지역 수 : "
        f"{len(facility_df)}개"
    )

    print(
        f"청년인구 지역 수 : "
        f"{len(population_df)}개"
    )


    # =====================================================
    # 25개 동 검사
    # =====================================================

    if len(facility_df) != 25:

        print()
        print(
            "주의:"
            " 공공시설 데이터가 25개 동이 아닙니다."
        )


    if len(population_df) != 25:

        print()
        print(
            "주의:"
            " 청년인구 데이터가 25개 동이 아닙니다."
        )


    # =====================================================
    # 공공시설 필수 컬럼 확인
    # =====================================================

    if (
        "청년공공시설수"
        not in facility_df.columns
    ):

        print()
        print(
            "'청년공공시설수' 컬럼이 없습니다."
        )

        return


    # =====================================================
    # 인구 컬럼 찾기
    # =====================================================

    population_column = (
        find_population_column(
            population_df
        )
    )


    if population_column is None:

        print()
        print(
            "2030 인구수 컬럼을 찾지 못했습니다."
        )

        print()
        print(
            "현재 인구 파일 컬럼:"
        )

        for column in population_df.columns:

            print(
                "-",
                column
            )

        return


    print()
    print(
        f"사용할 청년인구 컬럼 : "
        f"{population_column}"
    )


    # =====================================================
    # 인구 데이터 필요한 컬럼만 선택
    # =====================================================

    population_small = population_df[
        [
            "지역",
            population_column
        ]
    ].copy()


    population_small = population_small.rename(
        columns={
            population_column:
                "2030인구수"
        }
    )


    # =====================================================
    # 숫자형 변환
    # =====================================================

    population_small[
        "2030인구수"
    ] = to_numeric(
        population_small[
            "2030인구수"
        ]
    )


    facility_df[
        "청년공공시설수"
    ] = to_numeric(
        facility_df[
            "청년공공시설수"
        ]
    ).fillna(
        0
    )


    # =====================================================
    # 두 데이터 병합
    # =====================================================

    df = pd.merge(
        facility_df,
        population_small,
        on="지역",
        how="left",
        validate="one_to_one"
    )


    # =====================================================
    # 인구 연결 실패 검사
    # =====================================================

    missing_population = df[
        df[
            "2030인구수"
        ].isna()
    ]


    if not missing_population.empty:

        print()
        print(
            "청년인구가 연결되지 않은 지역:"
        )

        for region in (
            missing_population[
                "지역"
            ].tolist()
        ):

            print(
                "-",
                region
            )

        return


    # =====================================================
    # 인구 0 검사
    # =====================================================

    invalid_population = df[
        df[
            "2030인구수"
        ]
        <= 0
    ]


    if not invalid_population.empty:

        print()
        print(
            "2030 인구수가 0 이하인 지역이 있습니다."
        )

        return


    # =====================================================
    # 1,000명당 청년 공공시설 수
    # =====================================================

    df[
        "청년공공시설_1000명당"
    ] = (

        df[
            "청년공공시설수"
        ]

        /

        df[
            "2030인구수"
        ]

        * 1000

    ).round(
        3
    )


    # =====================================================
    # 시설 0개 여부
    # =====================================================

    df[
        "청년공공시설_0개"
    ] = (

        df[
            "청년공공시설수"
        ]
        == 0

    )


    # =====================================================
    # 25개 동 중앙값
    # =====================================================

    median_per_1000 = (

        df[
            "청년공공시설_1000명당"
        ]

        .median()

    )


    # =====================================================
    # 상대적 부족
    #
    # 25개 동 중앙값보다 낮으면 True
    #
    # 공식 정책기준이 아니라
    # 프로젝트 내부 상대비교 기준
    # =====================================================

    df[
        "공공시설_상대부족"
    ] = (

        df[
            "청년공공시설_1000명당"
        ]

        < median_per_1000

    )


    # =====================================================
    # 2030 인구 TOP10
    # =====================================================

    top10_indices = (

        df

        .sort_values(
            "2030인구수",
            ascending=False
        )

        .head(10)

        .index

    )


    df[
        "2030인구_TOP10"
    ] = False


    df.loc[
        top10_indices,
        "2030인구_TOP10"
    ] = True


    # =====================================================
    # 공공지원 인프라 점검 후보
    #
    # 청년 인구 TOP10이면서
    # 1,000명당 공공시설이 중앙값 미만
    #
    # 이것도 프로젝트 내부 탐색 기준
    # =====================================================

    df[
        "공공지원_점검후보"
    ] = (

        df[
            "2030인구_TOP10"
        ]

        &

        df[
            "공공시설_상대부족"
        ]

    )


    # =====================================================
    # 공급상태 설명
    # =====================================================

    def make_supply_status(row):

        if row[
            "청년공공시설_0개"
        ]:

            return "시설 없음"


        if row[
            "공공시설_상대부족"
        ]:

            return "청년인구 대비 상대부족"


        return "상대적으로 양호"


    df[
        "공공지원인프라_상태"
    ] = df.apply(
        make_supply_status,
        axis=1
    )


    # =====================================================
    # 세부 시설유형 1,000명당 계산
    # =====================================================

    type_columns = [

        "통합지원형_수",
        "취업지원형_수",
        "창업지원형_수",
        "프로그램운영형_수",
        "기타공간_수"
    ]


    for column in type_columns:

        if column not in df.columns:

            continue


        df[
            column
        ] = to_numeric(
            df[
                column
            ]
        ).fillna(
            0
        )


        new_column = (
            column
            .replace(
                "_수",
                "_1000명당"
            )
        )


        df[
            new_column
        ] = (

            df[
                column
            ]

            /

            df[
                "2030인구수"
            ]

            * 1000

        ).round(
            3
        )


    # =====================================================
    # 정렬
    #
    # 점검후보 우선
    # 그다음 청년인구 많은 순
    # =====================================================

    df = (

        df

        .sort_values(
            by=[
                "공공지원_점검후보",
                "2030인구수"
            ],
            ascending=[
                False,
                False
            ]
        )

        .reset_index(
            drop=True
        )

    )


    # =====================================================
    # 저장
    # =====================================================

    df.to_csv(
        OUTPUT_FILE,
        index=False,
        encoding="utf-8-sig"
    )


    # =====================================================
    # 결과 출력
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "공공시설 분석 완료"
    )

    print(
        "========================================"
    )


    print()
    print(
        f"분석 지역 : "
        f"{len(df)}개"
    )


    print(
        f"전체 청년 공공시설 : "
        f"{int(df['청년공공시설수'].sum())}개"
    )


    print(
        f"시설 0개 지역 : "
        f"{int(df['청년공공시설_0개'].sum())}개"
    )


    print(
        f"1,000명당 시설 중앙값 : "
        f"{median_per_1000:.3f}개"
    )


    shortage_count = int(
        df[
            "공공시설_상대부족"
        ].sum()
    )


    print(
        f"상대부족 지역 : "
        f"{shortage_count}개"
    )


    candidate_count = int(
        df[
            "공공지원_점검후보"
        ].sum()
    )


    print(
        f"공공지원 점검후보 : "
        f"{candidate_count}개"
    )


    # =====================================================
    # 시설 0개 지역
    # =====================================================

    print()
    print(
        "----------------------------------------"
    )

    print(
        "[청년 공공시설 0개 지역]"
    )

    print(
        "----------------------------------------"
    )


    zero_df = df[
        df[
            "청년공공시설_0개"
        ]
        == True
    ]


    for _, row in (
        zero_df.iterrows()
    ):

        print(
            f"- {row['지역']} "
            f"/ 2030인구 "
            f"{int(row['2030인구수']):,}명"
        )


    # =====================================================
    # 점검 후보지역
    # =====================================================

    print()
    print(
        "----------------------------------------"
    )

    print(
        "[공공지원 인프라 점검 후보]"
    )

    print(
        "----------------------------------------"
    )


    candidate_df = df[
        df[
            "공공지원_점검후보"
        ]
        == True
    ]


    if candidate_df.empty:

        print(
            "해당 지역 없음"
        )


    else:

        for _, row in (
            candidate_df.iterrows()
        ):

            print()

            print(
                f"[{row['지역']}]"
            )

            print(
                f"2030인구 : "
                f"{int(row['2030인구수']):,}명"
            )

            print(
                f"청년공공시설 : "
                f"{int(row['청년공공시설수'])}개"
            )

            print(
                f"1,000명당 : "
                f"{row['청년공공시설_1000명당']:.3f}개"
            )

            print(
                f"상태 : "
                f"{row['공공지원인프라_상태']}"
            )


    # =====================================================
    # 1,000명당 가장 낮은 지역 TOP 10
    # =====================================================

    print()
    print(
        "----------------------------------------"
    )

    print(
        "[청년 1,000명당 공공시설 낮은 지역 TOP 10]"
    )

    print(
        "----------------------------------------"
    )


    low10 = (

        df

        .sort_values(
            "청년공공시설_1000명당",
            ascending=True
        )

        .head(10)

    )


    for _, row in (
        low10.iterrows()
    ):

        print(
            f"- {row['지역']} : "
            f"{row['청년공공시설_1000명당']:.3f}개 "
            f"({int(row['청년공공시설수'])}개 / "
            f"{int(row['2030인구수']):,}명)"
        )


    # =====================================================
    # 중요 안내
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "해석 주의"
    )

    print(
        "========================================"
    )


    print(
        "※ '상대부족'은 공식 정책 기준이 아니라 "
        "25개 동 중앙값을 이용한 프로젝트 상대비교입니다."
    )

    print(
        "※ 시설 개수는 실제 이용인원·수용능력·서비스 품질을 "
        "반영하지 않습니다."
    )

    print(
        "※ 이 지표는 현재 HL-Score에는 반영하지 않고 "
        "정책지원 인프라 보조지표로 사용합니다."
    )


    print()
    print(
        "저장 위치:"
    )

    print(
        OUTPUT_FILE
    )


# =========================================================
# 실행
# =========================================================

if __name__ == "__main__":

    main()