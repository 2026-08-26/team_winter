from pathlib import Path

import pandas as pd


# =========================================================
# 1. 경로 설정
# =========================================================

BASE_DIR = Path(__file__).resolve().parent.parent

PROCESSED_DIR = (
    BASE_DIR
    / "data"
    / "processed"
)

INPUT_FILE = (
    PROCESSED_DIR
    / "청년소형주택_25개동_실거래.csv"
)

OUTPUT_FILE = (
    PROCESSED_DIR
    / "주거_중복민감도_분석.csv"
)


# =========================================================
# 2. 분석 기준
# =========================================================

DEPOSIT_ANNUAL_RATE = 0.05


# =========================================================
# 3. 행정동 매핑 과정에서 새로 붙인 컬럼
#
# 중복 판별에서는 제외한다.
# 즉 국토부 원본 거래정보만 비교한다.
# =========================================================

MAPPING_COLUMNS = [

    "주소키",

    "위도",
    "경도",

    "검색주소",
    "카카오매칭주소",

    "공식자치구",
    "공식행정동",
    "행정동코드",

    "매핑상태",

    "프로젝트자치구",
    "프로젝트행정동",

    "분석대상여부",

    "공식지역",
    "프로젝트지역"
]


# =========================================================
# 4. 숫자 변환
# =========================================================

def to_numeric(series):

    return pd.to_numeric(
        series.astype(str)
        .str.replace(
            ",",
            "",
            regex=False
        ),
        errors="coerce"
    )


# =========================================================
# 5. 데이터 정리
# =========================================================

def normalize_dataframe(df):

    result = df.copy()

    for column in result.columns:

        result[column] = (

            result[column]

            .fillna("")

            .astype(str)

            .str.strip()

        )

    return result


# =========================================================
# 6. 월환산주거비 계산
# =========================================================

def add_monthly_cost(df):

    result = df.copy()


    result[
        "보증금_만원"
    ] = to_numeric(
        result[
            "deposit"
        ]
    )


    result[
        "월세_만원"
    ] = to_numeric(
        result[
            "monthlyRent"
        ]
    )


    result[
        "월환산주거비_만원"
    ] = (

        result[
            "월세_만원"
        ]

        +

        (
            result[
                "보증금_만원"
            ]
            * DEPOSIT_ANNUAL_RATE
            / 12
        )

    )


    return result


# =========================================================
# 7. 동별 평균 계산
# =========================================================

def summarize_by_dong(
    df,
    prefix
):

    summary = (

        df

        .groupby(
            [
                "프로젝트자치구",
                "프로젝트행정동"
            ],
            as_index=False
        )

        .agg(

            거래건수=(
                "월환산주거비_만원",
                "size"
            ),

            평균주거비=(
                "월환산주거비_만원",
                "mean"
            )

        )

    )


    summary = summary.rename(
        columns={

            "거래건수":
                f"{prefix}_거래건수",

            "평균주거비":
                f"{prefix}_월환산주거비_평균"

        }
    )


    return summary


# =========================================================
# 8. 민감도 상태
#
# 아래 기준은 공식 기준이 아니라
# 프로젝트 내부 점검용이다.
# =========================================================

def sensitivity_status(percent):

    if pd.isna(
        percent
    ):

        return "비교불가"


    percent = abs(
        percent
    )


    if percent < 2:

        return "안정"


    elif percent < 5:

        return "주의"


    else:

        return "민감"


# =========================================================
# 9. 메인
# =========================================================

def main():

    print()
    print(
        "========================================"
    )

    print(
        "주거 실거래 중복 민감도 분석"
    )

    print(
        "========================================"
    )


    # =====================================================
    # 입력 확인
    # =====================================================

    if not INPUT_FILE.exists():

        print(
            "\n입력 파일이 없습니다."
        )

        print(
            INPUT_FILE
        )

        return


    # =====================================================
    # 데이터 읽기
    # =====================================================

    df = pd.read_csv(
        INPUT_FILE,
        encoding="utf-8-sig",
        dtype=str,
        keep_default_na=False
    )


    df = normalize_dataframe(
        df
    )


    print(
        f"\n현재 분석 거래 : "
        f"{len(df):,}건"
    )


    # =====================================================
    # 필수 컬럼 검사
    # =====================================================

    required_columns = [

        "프로젝트자치구",
        "프로젝트행정동",

        "deposit",
        "monthlyRent"
    ]


    missing = [

        column

        for column in required_columns

        if column not in df.columns
    ]


    if missing:

        print(
            "\n필수 컬럼 누락"
        )

        for column in missing:

            print(
                "-",
                column
            )

        return


    # =====================================================
    # A안
    #
    # 현재 데이터 그대로
    # =====================================================

    original_df = add_monthly_cost(
        df
    )


    # =====================================================
    # 원본 컬럼만 선택
    # =====================================================

    raw_columns = [

        column

        for column in df.columns

        if column not in MAPPING_COLUMNS

    ]


    # 혹시 우리가 이번 코드에서 만든 컬럼이 있으면 제외
    raw_columns = [

        column

        for column in raw_columns

        if column not in [

            "보증금_만원",
            "월세_만원",
            "월환산주거비_만원"

        ]

    ]


    print(
        f"중복 판별 원본 컬럼 : "
        f"{len(raw_columns)}개"
    )


    # =====================================================
    # B안
    #
    # 원본 모든 컬럼이 완전히 같은 행은
    # 첫 번째 1건만 남긴 가상 시나리오
    # =====================================================

    dedup_df = (

        df

        .drop_duplicates(
            subset=raw_columns,
            keep="first"
        )

        .copy()

    )


    dedup_df = add_monthly_cost(
        dedup_df
    )


    removed_count = (

        len(df)
        -
        len(dedup_df)

    )


    print()
    print(
        f"A안 현재 거래 : "
        f"{len(original_df):,}건"
    )

    print(
        f"B안 중복제거 가정 : "
        f"{len(dedup_df):,}건"
    )

    print(
        f"제거되는 가정 행 : "
        f"{removed_count:,}건"
    )


    # =====================================================
    # 동별 A안 계산
    # =====================================================

    current_summary = summarize_by_dong(
        original_df,
        "현재"
    )


    # =====================================================
    # 동별 B안 계산
    # =====================================================

    dedup_summary = summarize_by_dong(
        dedup_df,
        "중복제거가정"
    )


    # =====================================================
    # 결합
    # =====================================================

    result = current_summary.merge(

        dedup_summary,

        on=[
            "프로젝트자치구",
            "프로젝트행정동"
        ],

        how="outer"

    )


    # =====================================================
    # 지역 표시
    # =====================================================

    result[
        "지역"
    ] = (

        result[
            "프로젝트자치구"
        ].astype(str)

        + " "

        + result[
            "프로젝트행정동"
        ].astype(str)

    )


    # =====================================================
    # 제거 거래 수
    # =====================================================

    result[
        "제거가정_거래건수"
    ] = (

        result[
            "현재_거래건수"
        ]

        -

        result[
            "중복제거가정_거래건수"
        ]

    )


    # =====================================================
    # 평균값 반올림
    # =====================================================

    result[
        "현재_월환산주거비_평균"
    ] = (

        result[
            "현재_월환산주거비_평균"
        ]

        .round(2)

    )


    result[
        "중복제거가정_월환산주거비_평균"
    ] = (

        result[
            "중복제거가정_월환산주거비_평균"
        ]

        .round(2)

    )


    # =====================================================
    # 절대 차이
    # =====================================================

    result[
        "평균차이_만원"
    ] = (

        result[
            "중복제거가정_월환산주거비_평균"
        ]

        -

        result[
            "현재_월환산주거비_평균"
        ]

    ).round(2)


    # =====================================================
    # 변화율
    # =====================================================

    result[
        "변화율_pct"
    ] = (

        (
            result[
                "중복제거가정_월환산주거비_평균"
            ]

            -

            result[
                "현재_월환산주거비_평균"
            ]
        )

        /

        result[
            "현재_월환산주거비_평균"
        ]

        * 100

    ).round(2)


    # =====================================================
    # 민감도 상태
    # =====================================================

    result[
        "민감도판정"
    ] = (

        result[
            "변화율_pct"
        ]

        .apply(
            sensitivity_status
        )

    )


    # =====================================================
    # 주거비 순위
    #
    # 낮은 주거비 = 1위
    # =====================================================

    result[
        "현재_주거비순위"
    ] = (

        result[
            "현재_월환산주거비_평균"
        ]

        .rank(
            method="min",
            ascending=True
        )

        .astype(
            "Int64"
        )

    )


    result[
        "중복제거가정_주거비순위"
    ] = (

        result[
            "중복제거가정_월환산주거비_평균"
        ]

        .rank(
            method="min",
            ascending=True
        )

        .astype(
            "Int64"
        )

    )


    result[
        "순위변화"
    ] = (

        result[
            "중복제거가정_주거비순위"
        ]

        -

        result[
            "현재_주거비순위"
        ]

    )


    # =====================================================
    # 보기 좋은 컬럼 순서
    # =====================================================

    result = result[

        [

            "프로젝트자치구",
            "프로젝트행정동",
            "지역",

            "현재_거래건수",
            "중복제거가정_거래건수",
            "제거가정_거래건수",

            "현재_월환산주거비_평균",
            "중복제거가정_월환산주거비_평균",

            "평균차이_만원",
            "변화율_pct",

            "현재_주거비순위",
            "중복제거가정_주거비순위",
            "순위변화",

            "민감도판정"

        ]

    ]


    # =====================================================
    # 저장
    # =====================================================

    result.to_csv(
        OUTPUT_FILE,
        index=False,
        encoding="utf-8-sig"
    )


    # =====================================================
    # 결과 요약
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "민감도 분석 결과"
    )

    print(
        "========================================"
    )


    status_count = (

        result[
            "민감도판정"
        ]

        .value_counts()

    )


    for status, count in (
        status_count.items()
    ):

        print(
            f"{status} : "
            f"{count}개 동"
        )


    # =====================================================
    # 가장 많이 변한 지역
    # =====================================================

    result[
        "절대변화율"
    ] = (

        result[
            "변화율_pct"
        ]

        .abs()

    )


    top_changed = (

        result

        .sort_values(
            "절대변화율",
            ascending=False
        )

        .head(10)

    )


    print()
    print(
        "----------------------------------------"
    )

    print(
        "중복 처리에 가장 민감한 지역 TOP 10"
    )

    print(
        "----------------------------------------"
    )


    for _, row in (
        top_changed.iterrows()
    ):

        print()

        print(
            f"[{row['지역']}]"
        )

        print(
            f"거래 : "
            f"{row['현재_거래건수']}건"
            f" → "
            f"{row['중복제거가정_거래건수']}건"
        )

        print(
            f"평균 : "
            f"{row['현재_월환산주거비_평균']}만원"
            f" → "
            f"{row['중복제거가정_월환산주거비_평균']}만원"
        )

        print(
            f"차이 : "
            f"{row['평균차이_만원']}만원"
        )

        print(
            f"변화율 : "
            f"{row['변화율_pct']}%"
        )

        print(
            f"순위 : "
            f"{row['현재_주거비순위']}"
            f" → "
            f"{row['중복제거가정_주거비순위']}"
        )

        print(
            f"판정 : "
            f"{row['민감도판정']}"
        )


    # =====================================================
    # 두암2동 별도 확인
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "두암2동 확인"
    )

    print(
        "========================================"
    )


    duam = result[
        result[
            "프로젝트행정동"
        ]
        == "두암2동"
    ]


    if not duam.empty:

        row = duam.iloc[0]

        print(
            f"현재 거래 : "
            f"{row['현재_거래건수']}건"
        )

        print(
            f"중복 제거 가정 : "
            f"{row['중복제거가정_거래건수']}건"
        )

        print(
            f"현재 평균 : "
            f"{row['현재_월환산주거비_평균']}만원"
        )

        print(
            f"중복 제거 평균 : "
            f"{row['중복제거가정_월환산주거비_평균']}만원"
        )


    # =====================================================
    # 최종 전체 요약
    # =====================================================

    max_change = (

        result[
            "변화율_pct"
        ]

        .abs()

        .max()

    )


    mean_change = (

        result[
            "변화율_pct"
        ]

        .abs()

        .mean()

    )


    print()
    print(
        "========================================"
    )

    print(
        "전체 민감도 요약"
    )

    print(
        "========================================"
    )


    print(
        f"평균 절대 변화율 : "
        f"{mean_change:.2f}%"
    )

    print(
        f"최대 절대 변화율 : "
        f"{max_change:.2f}%"
    )


    sensitive_count = (

        result[
            "민감도판정"
        ]
        == "민감"

    ).sum()


    print(
        f"5% 이상 변화 지역 : "
        f"{sensitive_count}개 동"
    )


    print()
    print(
        "※ 민감도 판정은 프로젝트 내부 품질점검 기준입니다."
    )

    print(
        "※ 이 분석에서는 실제 데이터를 삭제하지 않습니다."
    )

    print(
        "※ 중복제거 가정은 결과 안정성 확인을 위한 비교 시나리오입니다."
    )


    print()
    print(
        "----------------------------------------"
    )

    print(
        "결과 저장 :"
    )

    print(
        OUTPUT_FILE
    )

    print(
        "----------------------------------------"
    )


if __name__ == "__main__":

    main()