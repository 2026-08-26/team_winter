# =========================================================
# 6. 좌표 → 공식 행정동
# =========================================================

def get_admin_region(
    longitude,
    latitude
):

    if (
        pd.isna(longitude)
        or
        pd.isna(latitude)
    ):

        return {
            "공식자치구": "",
            "공식행정동": "",
            "행정동코드": "",
            "행정동매핑상태": "좌표없음"
        }


    params = {
        "x": longitude,
        "y": latitude
    }


    # 일시적인 통신오류를 대비해 최대 3번
    for attempt in range(3):

        try:

            response = requests.get(
                REGION_URL,
                headers=HEADERS,
                params=params,
                timeout=15
            )

            response.raise_for_status()

            data = response.json()

            documents = data.get(
                "documents",
                []
            )


            # H = 행정동
            admin_regions = [
                item
                for item in documents
                if item.get(
                    "region_type"
                ) == "H"
            ]


            if admin_regions:

                item = admin_regions[0]

                return {
                    "공식자치구":
                        item.get(
                            "region_2depth_name",
                            ""
                        ),

                    "공식행정동":
                        item.get(
                            "region_3depth_name",
                            ""
                        ),

                    "행정동코드":
                        item.get(
                            "code",
                            ""
                        ),

                    "행정동매핑상태":
                        "성공"
                }


            return {
                "공식자치구": "",
                "공식행정동": "",
                "행정동코드": "",
                "행정동매핑상태": "행정동결과없음"
            }


        except Exception as e:

            if attempt == 2:

                print(
                    f"행정동 변환 오류 : {e}"
                )

                return {
                    "공식자치구": "",
                    "공식행정동": "",
                    "행정동코드": "",
                    "행정동매핑상태": "API오류"
                }

            time.sleep(
                1
            )


# =========================================================
# 7. 공식 행정동 → 프로젝트 25개 동 확인
# =========================================================

def convert_to_project_region(
    source_gu,
    source_dong
):

    for target in TARGET_DONGS:

        if (
            target["공식자치구"]
            == source_gu
            and
            target["행정동"]
            == source_dong
        ):

            return {
                "프로젝트자치구":
                    target[
                        "프로젝트자치구"
                    ],

                "프로젝트행정동":
                    target[
                        "행정동"
                    ],

                "분석대상여부":
                    True
            }


    # 25개 동이 아닌 경우
    return {
        "프로젝트자치구":
            source_gu,

        "프로젝트행정동":
            source_dong,

        "분석대상여부":
            False
    }


