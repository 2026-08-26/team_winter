# =========================================================
# 2. 문자열 정리
# =========================================================

def clean_text(value):

    if pd.isna(value):
        return ""

    text = str(
        value
    ).strip()

    if text.lower() in [
        "nan",
        "none"
    ]:
        return ""

    return text


# =========================================================
# 3. True / False 변환
# =========================================================

def to_bool(value):

    if isinstance(
        value,
        bool
    ):
        return value

    text = str(
        value
    ).strip().lower()

    return text in [
        "true",
        "1",
        "yes",
        "y"
    ]


# =========================================================
# 4. 정책 신호 여부
# =========================================================

def has_existing_policy_signal(
    policy_type
):

    policy_type = clean_text(
        policy_type
    )

    return (
        policy_type
        not in [
            "",
            "일반 관찰",
            "HL순위 제외"
        ]
    )


# =========================================================
# 5. 버스 정류소 정책 해석
# =========================================================

def make_bus_note(row):

    stop_count = int(
        row[
            "공식정류소수"
        ]
    )

    per_1000 = float(
        row[
            "청년1000명당_정류소수"
        ]
    )

    shortage = to_bool(
        row[
            "정류소공급_상대부족"
        ]
    )

    candidate = to_bool(
        row[
            "청년교통공급_점검후보"
        ]
    )


    # -----------------------------------------------------
    # 청년인구 TOP10 + 상대부족
    # -----------------------------------------------------

    if candidate:

        return (
            f"행정동 내부 공식 버스정류소 "
            f"{stop_count:,}개, "
            f"2030 청년 1,000명당 "
            f"{per_1000:.2f}개로 "
            "25개 분석대상 동 중앙값보다 낮으며, "
            "청년인구 규모도 큰 지역이어서 "
            "대중교통 공급여건의 추가 점검이 필요한 지역."
        )


    # -----------------------------------------------------
    # 중앙값 미만
    # -----------------------------------------------------

    if shortage:

        return (
            f"행정동 내부 공식 버스정류소 "
            f"{stop_count:,}개, "
            f"2030 청년 1,000명당 "
            f"{per_1000:.2f}개로 "
            "25개 분석대상 동 중앙값보다 낮아 "
            "정류소 공급여건을 참고할 필요가 있는 지역."
        )


    return (
        f"행정동 내부 공식 버스정류소 "
        f"{stop_count:,}개, "
        f"2030 청년 1,000명당 "
        f"{per_1000:.2f}개. "
        "현재 프로젝트 상대비교에서는 "
        "정류소 공급 부족 신호가 확인되지 않은 지역."
    )


# =========================================================
# 6. 기존 정책 + 교통 보조신호
# =========================================================

def make_bus_combined_signal(row):

    policy_type = clean_text(
        row.get(
            "최종정책유형",
            ""
        )
    )

    candidate = to_bool(
        row[
            "청년교통공급_점검후보"
        ]
    )

    shortage = to_bool(
        row[
            "정류소공급_상대부족"
        ]
    )


    existing_signal = (
        has_existing_policy_signal(
            policy_type
        )
    )


    if (
        existing_signal
        and candidate
    ):

        return (
            "기존 정책신호 + "
            "청년 대중교통 공급 점검"
        )


    if candidate:

        return (
            "청년 대중교통 공급 점검"
        )


    if (
        existing_signal
        and shortage
    ):

        return (
            "기존 정책신호 + "
            "정류소 공급여건 참고"
        )


    if existing_signal:

        return "기존 정책신호"


    if shortage:

        return "정류소 공급여건 참고"


    return "추가 교통공급 신호 없음"


