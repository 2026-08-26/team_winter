# 4. 최종 정책유형 판단
# =========================================================

def make_final_policy_type(row):

    hl_grade = clean_text(
        row.get(
            "HL정책검토등급",
            ""
        )
    )

    demand_candidate = to_bool(
        row.get(
            "수요대비인프라후보",
            False
        )
    )

    demand_priority = to_bool(
        row.get(
            "수요대비우선후보",
            False
        )
    )


    # =====================================================
    # A. HL 정책순위 제외지역
    #
    # 예: 두암2동
    #
    # HL 순위에서는 제외하되
    # 청년수요 분석 결과까지 버리지는 않음
    # =====================================================

    if hl_grade == "정책순위 제외":

        if demand_priority:

            return (
                "수요분석 우선 · HL순위 제외"
            )


        if demand_candidate:

            return (
                "수요분석 검토 · HL순위 제외"
            )


        return "HL순위 제외"


    # =====================================================
    # B. 두 분석 모두에서 신호
    # =====================================================

    if (
        hl_grade == "우선 개선 검토"
        and demand_priority
    ):

        return "복합 최우선 검토"


    if (
        hl_grade == "우선 개선 검토"
        and demand_candidate
    ):

        return "복합 정책검토"


    if (
        hl_grade == "관심 검토"
        and demand_priority
    ):

        return "복합 우선 검토"


    if (
        hl_grade == "관심 검토"
        and demand_candidate
    ):

        return "복합 관심 검토"


    # =====================================================
    # C. HL 분석 단독 신호
    # =====================================================

    if hl_grade == "우선 개선 검토":

        return "주거환경 개선 우선"


    if hl_grade == "관심 검토":

        return "주거환경 관심 검토"


    # =====================================================
    # D. 청년수요 분석 단독 신호
    # =====================================================

    if demand_priority:

        return "청년수요 대응 우선"


    if demand_candidate:

        return (
            "청년수요 대비 인프라 검토"
        )


    return "일반 관찰"


