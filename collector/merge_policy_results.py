# 7. 통합 정책제안
# =========================================================

def make_integrated_policy_recommendation(row):

    suggestions = []

    hl_grade = clean_text(
        row.get(
            "HL정책검토등급",
            ""
        )
    )

    hl_factors = clean_text(
        row.get(
            "HL주요취약요인",
            ""
        )
    )

    shortage = clean_text(
        row.get(
            "수요대비부족분야",
            ""
        )
    )


    # =====================================================
    # 정책순위 제외
    # =====================================================

    if hl_grade == "정책순위 제외":

        suggestions.append(
            "주거 실거래 표본 추가 확보 후 "
            "HL-Score 재평가"
        )


    # =====================================================
    # 두 분석 동시 신호
    # =====================================================

    if row[
        "두분석_동시신호"
    ]:

        suggestions.append(
            "주거·교통·생활환경 통합 "
            "현장진단 우선 검토"
        )


    # =====================================================
    # 생활 인프라
    # =====================================================

    if (
        "생활인프라" in hl_factors
        or (
            row[
                "수요대비인프라후보"
            ]
            and "생활 인프라" in shortage
        )
    ):

        suggestions.append(
            "생활SOC·의료·편의·문화시설 "
            "공급 및 접근성 점검"
        )


    # =====================================================
    # 청년 선호시설
    # =====================================================

    if (
        "2030선호시설" in hl_factors
        or (
            row[
                "수요대비인프라후보"
            ]
            and "2030 선호시설" in shortage
        )
    ):

        suggestions.append(
            "청년 문화·운동·생활편의시설 "
            "공급 확대 가능성 검토"
        )


    # =====================================================
    # 교통
    # =====================================================

    if (
        "교통접근성" in hl_factors
        or (
            row[
                "수요대비인프라후보"
            ]
            and "교통" in shortage
        )
    ):

        suggestions.append(
            "노선 수·배차간격을 포함한 "
            "대중교통 서비스 수준 점검"
        )


    # =====================================================
    # 주거
    # =====================================================

    if "주거가성비" in hl_factors:

        suggestions.append(
            "청년 주거비 부담 완화 및 "
            "공공임대 연계 가능성 검토"
        )


    # =====================================================
    # 아무 제안도 없을 경우
    # =====================================================

    if len(
        suggestions
    ) == 0:

        suggestions.append(
            "청년 인구와 주거환경 변화의 "
            "지속 모니터링"
        )


    # =====================================================
    # 중복 문구 제거
    # =====================================================

    unique_suggestions = []


    for suggestion in suggestions:

        if (
            suggestion
            not in unique_suggestions
        ):

            unique_suggestions.append(
                suggestion
            )


    return " · ".join(
        unique_suggestions
    )


