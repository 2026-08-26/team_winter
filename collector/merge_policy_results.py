# 6. 임원 보고용 핵심 진단
# =========================================================

def make_policy_evidence(row):

    hl_grade = clean_text(
        row.get(
            "HL정책검토등급",
            ""
        )
    )

    weak_factor = clean_text(
        row.get(
            "HL주요취약요인",
            ""
        )
    )

    shortage = clean_text(
        row.get(
            "수요대비부족분야",
            ""
        )
    )


    if not shortage:

        shortage = "일부 인프라"


    weak_exists = (

        weak_factor
        and weak_factor != "없음"

    )


    # =====================================================
    # ① HL 정책순위 제외
    # =====================================================

    if hl_grade == "정책순위 제외":

        if row[
            "수요대비우선후보"
        ]:

            return (
                "주거 실거래 표본부족으로 "
                "HL 정책순위 비교에서는 제외되지만, "
                "청년수요 분석에서는 우선 후보로 확인됨. "
                f"청년 인구 대비 {shortage} 공급 수준의 "
                "추가 점검이 필요한 지역."
            )


        if row[
            "수요대비인프라후보"
        ]:

            return (
                "주거 실거래 표본부족으로 "
                "HL 정책순위 비교에서는 제외되지만, "
                f"청년 인구 대비 {shortage} 공급이 "
                "상대적으로 부족하게 나타난 지역."
            )


        return (
            "주거 실거래 표본이 5건 미만으로 "
            "HL 정책순위 비교에서 제외된 지역. "
            "충분한 주거 거래 표본 확보 후 "
            "재평가가 필요함."
        )


    # =====================================================
    # ② 두 분석 모두 신호
    # =====================================================

    if row[
        "두분석_동시신호"
    ]:

        if weak_exists:

            text = (
                f"HL-Score 분석에서 {weak_factor} "
                "취약 신호가 나타났으며, "
                f"청년 인구 대비 {shortage} 공급도 "
                "상대적으로 부족한 지역."
            )

        else:

            text = (
                "HL-Score가 상대적으로 낮게 나타났으며, "
                f"청년 인구 대비 {shortage} 공급도 "
                "상대적으로 부족한 지역."
            )


        return add_sample_warning(
            text,
            row
        )


    # =====================================================
    # ③ HL 우선 개선
    # =====================================================

    if hl_grade == "우선 개선 검토":

        if weak_exists:

            text = (
                "HL-Score 상대 하위권 지역으로, "
                f"{weak_factor} 부문의 "
                "우선 점검이 필요한 지역."
            )

        else:

            text = (
                "HL-Score 상대 하위권 지역으로, "
                "종합적인 주거환경 수준에 대한 "
                "우선 점검이 필요한 지역."
            )


        return add_sample_warning(
            text,
            row
        )


    # =====================================================
    # ④ 청년수요 우선
    # =====================================================

    if row[
        "수요대비우선후보"
    ]:

        text = (
            "2030 청년 수요가 큰 반면 "
            f"{shortage} 공급 수준이 "
            "상대적으로 낮은 지역."
        )


        return add_sample_warning(
            text,
            row
        )


    # =====================================================
    # ⑤ HL 관심
    # =====================================================

    if hl_grade == "관심 검토":

        if weak_exists:

            text = (
                "HL-Score 분석에서 "
                f"{weak_factor} 부문의 "
                "추가 점검 필요성이 확인된 지역."
            )

        else:

            text = (
                "HL-Score 상대 비교에서 "
                "관심 검토권에 포함되었으나, "
                "개별 지표 중 뚜렷한 하위 25% "
                "취약요인은 확인되지 않은 지역."
            )


        return add_sample_warning(
            text,
            row
        )


    # =====================================================
    # ⑥ 청년수요 후보
    # =====================================================

    if row[
        "수요대비인프라후보"
    ]:

        text = (
            f"청년 인구 대비 {shortage} 공급 수준이 "
            "25개 분석대상 동 중앙값보다 "
            "낮게 나타난 지역."
        )


        return add_sample_warning(
            text,
            row
        )


    # =====================================================
    # ⑦ 일반
    # =====================================================

    text = (
        "현재 프로젝트 분석 기준에서는 "
        "높은 정책 우선 신호가 "
        "확인되지 않은 지역."
    )


    return add_sample_warning(
        text,
        row
    )


