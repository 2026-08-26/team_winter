# 5. 저표본 주의문 추가
# =========================================================

def add_sample_warning(
    text,
    row
):

    sample_status = clean_text(
        row.get(
            "HL주거표본판정",
            ""
        )
    )


    if sample_status == "저표본 주의":

        return (
            text
            + " 단, 주거 실거래 표본이 "
            + "5~19건으로 주거비 해석에 주의가 필요함."
        )


    return text


