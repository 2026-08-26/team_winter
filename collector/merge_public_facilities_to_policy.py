from pathlib import Path

import pandas as pd


# =========================================================
# 1. 경로
# =========================================================

BASE_DIR = Path(__file__).resolve().parent.parent

PROCESSED_DIR = (
    BASE_DIR
    / "data"
    / "processed"
)

POLICY_FILE = (
    PROCESSED_DIR
    / "청년주거환경_정책통합분석.csv"
)

PUBLIC_FACILITY_FILE = (
    PROCESSED_DIR
    / "2030_청년인구_대비_공공시설_분석.csv"
)

OUTPUT_FILE = (
    PROCESSED_DIR
    / "청년주거환경_정책통합분석_공공시설반영.csv"
)


# =========================================================
# 2. True / False 안전 변환
# =========================================================

def to_bool(value):

    if isinstance(value, bool):
        return value

    text = str(value).strip().lower()

    return text in [
        "true",
        "1",
        "yes",
        "y"
    ]


# =========================================================
# 3. 문자열 정리
# =========================================================

def clean_text(value):

    if pd.isna(value):
        return ""

    text = str(value).strip()

    if text.lower() in [
        "nan",
        "none"
    ]:
        return ""

    return text


# =========================================================
# 4. 공공지원 보조 진단
# =========================================================

def make_public_facility_evidence(row):

    facility_count = int(
        row[
            "청년공공시설수"
        ]
    )

    per_1000 = float(
        row[
            "청년공공시설_1000명당"
        ]
    )

    shortage = to_bool(
        row[
            "공공시설_상대부족"
        ]
    )

    candidate = to_bool(
        row[
            "공공지원_점검후보"
        ]
    )


    # -----------------------------------------------------
    # 시설 자체가 0개
    # -----------------------------------------------------

    if facility_count == 0:

        return (
            "분석대상 행정동 내 청년 공공시설이 "
            "확인되지 않아 공공지원 인프라의 "
            "추가 점검이 필요한 지역."
        )


    # -----------------------------------------------------
    # 인구 TOP10 + 상대부족
    # -----------------------------------------------------

    if candidate:

        return (
            f"청년 공공시설은 {facility_count}개이나 "
            f"2030 인구 1,000명당 {per_1000:.3f}개로, "
            "청년 인구 규모를 고려할 때 "
            "공공지원 인프라가 상대적으로 부족한 지역."
        )


    # -----------------------------------------------------
    # 상대부족
    # -----------------------------------------------------

    if shortage:

        return (
            f"청년 공공시설은 {facility_count}개이며 "
            f"2030 인구 1,000명당 {per_1000:.3f}개로, "
            "25개 분석대상 동 중앙값보다 낮은 지역."
        )


    # -----------------------------------------------------
    # 상대적으로 양호
    # -----------------------------------------------------

    return (
        f"청년 공공시설 {facility_count}개, "
        f"2030 인구 1,000명당 {per_1000:.3f}개로 "
        "현재 프로젝트 상대비교에서는 "
        "공공지원 인프라 부족 신호가 확인되지 않은 지역."
    )


# =========================================================
# 5. 공공지원 정책 검토 방향
# =========================================================

def make_public_facility_policy(row):

    facility_count = int(
        row[
            "청년공공시설수"
        ]
    )

    candidate = to_bool(
        row[
            "공공지원_점검후보"
        ]
    )

    shortage = to_bool(
        row[
            "공공시설_상대부족"
        ]
    )


    if facility_count == 0:

        return (
            "청년지원 공간의 신규 설치 필요성 또는 "
            "인접 행정동 시설과의 접근성·연계성 검토"
        )


    if candidate:

        return (
            "청년 인구 규모를 고려한 청년지원시설 "
            "공급 확대 및 기존 시설의 수용능력·접근성 점검"
        )


    if shortage:

        return (
            "기존 청년 공공시설의 접근성·서비스 범위와 "
            "추가 공급 필요성 검토"
        )


    return (
        "현재 시설 공급 수준을 유지하면서 "
        "이용률과 프로그램 운영성과 지속 모니터링"
    )


# =========================================================
# 6. 기존 정책 신호 + 공공시설 신호 관계
# =========================================================

def make_combined_signal(row):

    policy_type = clean_text(
        row.get(
            "최종정책유형",
            ""
        )
    )

    candidate = to_bool(
        row.get(
            "공공지원_점검후보",
            False
        )
    )

    zero_facility = to_bool(
        row.get(
            "청년공공시설_0개",
            False
        )
    )


    # 기존 정책 검토 신호 여부
    policy_signal = (
        policy_type
        not in [
            "",
            "일반 관찰",
            "HL순위 제외"
        ]
    )


    if (
        policy_signal
        and candidate
    ):

        return "기존 정책신호 + 공공지원 부족"


    if (
        policy_signal
        and zero_facility
    ):

        return "기존 정책신호 + 공공시설 없음"


    if policy_signal:

        return "기존 정책신호"


    if candidate:

        return "공공지원 부족 신호"


    if zero_facility:

        return "공공시설 없음"


    return "추가 신호 없음"


# =========================================================
# 7. 메인
# =========================================================

def main():

    print()
    print(
        "========================================"
    )

    print(
        "청년 공공시설 → 정책통합분석 병합"
    )

    print(
        "========================================"
    )


    # =====================================================
    # 파일 확인
    # =====================================================

    if not POLICY_FILE.exists():

        print()
        print(
            "정책통합분석 파일이 없습니다."
        )

        print(
            POLICY_FILE
        )

        return


    if not PUBLIC_FACILITY_FILE.exists():

        print()
        print(
            "청년 공공시설 분석 파일이 없습니다."
        )

        print(
            PUBLIC_FACILITY_FILE
        )

        return


    # =====================================================
    # 파일 읽기
    # =====================================================

    policy_df = pd.read_csv(
        POLICY_FILE,
        encoding="utf-8-sig"
    )

    facility_df = pd.read_csv(
        PUBLIC_FACILITY_FILE,
        encoding="utf-8-sig"
    )


    print()
    print(
        f"정책통합분석 : "
        f"{len(policy_df)}개 지역"
    )

    print(
        f"공공시설분석 : "
        f"{len(facility_df)}개 지역"
    )


    # =====================================================
    # 25개 동 검사
    # =====================================================

    if len(policy_df) != 25:

        print()
        print(
            "오류:"
            " 정책통합분석이 25개 동이 아닙니다."
        )

        return


    if len(facility_df) != 25:

        print()
        print(
            "오류:"
            " 공공시설분석이 25개 동이 아닙니다."
        )

        return


    # =====================================================
    # 지역 중복 검사
    # =====================================================

    if (
        policy_df[
            "지역"
        ]
        .duplicated()
        .any()
    ):

        print()
        print(
            "오류:"
            " 정책통합분석에 중복 지역이 있습니다."
        )

        return


    if (
        facility_df[
            "지역"
        ]
        .duplicated()
        .any()
    ):

        print()
        print(
            "오류:"
            " 공공시설분석에 중복 지역이 있습니다."
        )

        return


    # =====================================================
    # 공공시설에서 가져올 컬럼
    # =====================================================

    facility_columns = [

        "지역",

        "청년공공시설수",

        "청년공공시설_1000명당",

        "청년공공시설_0개",

        "공공시설_상대부족",

        "공공지원_점검후보",

        "공공지원인프라_상태",

        "통합지원형_수",

        "취업지원형_수",

        "창업지원형_수",

        "프로그램운영형_수",

        "기타공간_수"
    ]


    facility_columns = [

        column

        for column in facility_columns

        if column
        in facility_df.columns

    ]


    facility_small = facility_df[
        facility_columns
    ].copy()


    # =====================================================
    # 병합
    # =====================================================

    merged = pd.merge(
        policy_df,
        facility_small,
        on="지역",
        how="left",
        validate="one_to_one"
    )


    # =====================================================
    # 연결 실패 검사
    # =====================================================

    missing = merged[
        merged[
            "청년공공시설수"
        ].isna()
    ]


    if not missing.empty:

        print()
        print(
            "공공시설 데이터가 연결되지 않은 지역:"
        )

        for region in (
            missing[
                "지역"
            ].tolist()
        ):

            print(
                "-",
                region
            )

        return


    # =====================================================
    # Boolean 정리
    # =====================================================

    bool_columns = [

        "청년공공시설_0개",

        "공공시설_상대부족",

        "공공지원_점검후보"
    ]


    for column in bool_columns:

        merged[
            column
        ] = (

            merged[
                column
            ]

            .apply(
                to_bool
            )

        )


    # =====================================================
    # 공공시설 보조 정책근거
    # =====================================================

    merged[
        "공공지원_보조근거"
    ] = merged.apply(
        make_public_facility_evidence,
        axis=1
    )


    # =====================================================
    # 공공시설 정책검토 방향
    # =====================================================

    merged[
        "공공지원_정책검토방향"
    ] = merged.apply(
        make_public_facility_policy,
        axis=1
    )


    # =====================================================
    # 기존 정책 + 공공시설 관계
    # =====================================================

    merged[
        "정책_공공지원_통합신호"
    ] = merged.apply(
        make_combined_signal,
        axis=1
    )


    # =====================================================
    # HL 점수에는 미반영임을 명시
    # =====================================================

    merged[
        "공공시설_HL반영여부"
    ] = False


    merged[
        "공공시설지표_역할"
    ] = (
        "HL-Score 미반영 / "
        "정책지원 인프라 보조지표"
    )


    # =====================================================
    # 저장
    # =====================================================

    merged.to_csv(
        OUTPUT_FILE,
        index=False,
        encoding="utf-8-sig"
    )


    # =====================================================
    # 결과 출력
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "공공시설 정책통합 완료"
    )

    print(
        "========================================"
    )


    print(
        f"\n최종 지역 수 : "
        f"{len(merged)}개"
    )


    print(
        f"전체 청년공공시설 : "
        f"{int(merged['청년공공시설수'].sum())}개"
    )


    zero_count = int(
        merged[
            "청년공공시설_0개"
        ].sum()
    )


    print(
        f"공공시설 0개 지역 : "
        f"{zero_count}개"
    )


    candidate_count = int(
        merged[
            "공공지원_점검후보"
        ].sum()
    )


    print(
        f"공공지원 점검후보 : "
        f"{candidate_count}개"
    )


    # =====================================================
    # 기존 정책 + 공공시설 동시 신호
    # =====================================================

    print()
    print(
        "----------------------------------------"
    )

    print(
        "[기존 정책검토 + 공공지원 부족 동시 신호]"
    )

    print(
        "----------------------------------------"
    )


    combined = merged[
        merged[
            "정책_공공지원_통합신호"
        ].isin(
            [
                "기존 정책신호 + 공공지원 부족",
                "기존 정책신호 + 공공시설 없음"
            ]
        )
    ]


    if combined.empty:

        print(
            "해당 지역 없음"
        )


    else:

        for _, row in (
            combined.iterrows()
        ):

            print()

            print(
                f"[{row['지역']}]"
            )

            print(
                f"기존 정책유형 : "
                f"{row['최종정책유형']}"
            )

            print(
                f"청년공공시설 : "
                f"{int(row['청년공공시설수'])}개"
            )

            print(
                f"1,000명당 : "
                f"{row['청년공공시설_1000명당']:.3f}개"
            )

            print(
                f"통합신호 : "
                f"{row['정책_공공지원_통합신호']}"
            )

            print(
                f"보조근거 : "
                f"{row['공공지원_보조근거']}"
            )


    # =====================================================
    # 공공지원 점검후보
    # =====================================================

    print()
    print(
        "----------------------------------------"
    )

    print(
        "[공공지원 점검후보 전체]"
    )

    print(
        "----------------------------------------"
    )


    candidates = merged[
        merged[
            "공공지원_점검후보"
        ]
        == True
    ]


    for _, row in (
        candidates.iterrows()
    ):

        print(
            f"- {row['지역']} "
            f"→ {row['최종정책유형']} "
            f"/ {row['청년공공시설_1000명당']:.3f}개/1,000명"
        )


    # =====================================================
    # 공공시설 0개 지역
    # =====================================================

    print()
    print(
        "----------------------------------------"
    )

    print(
        "[청년 공공시설 0개 지역]"
    )

    print(
        "----------------------------------------"
    )


    zero_df = merged[
        merged[
            "청년공공시설_0개"
        ]
        == True
    ]


    for _, row in (
        zero_df.iterrows()
    ):

        print(
            f"- {row['지역']} "
            f"→ {row['최종정책유형']}"
        )


    # =====================================================
    # 중요 안내
    # =====================================================

    print()
    print(
        "========================================"
    )

    print(
        "주의"
    )

    print(
        "========================================"
    )


    print(
        "※ 청년 공공시설 지표는 "
        "HL-Score에 추가하지 않았습니다."
    )

    print(
        "※ 공공지원 점검후보는 "
        "공식 정책대상 선정 기준이 아닙니다."
    )

    print(
        "※ 시설 수는 이용인원·수용능력·서비스 품질을 "
        "직접 반영하지 않습니다."
    )


    print()
    print(
        "새 파일 저장:"
    )

    print(
        OUTPUT_FILE
    )


    print()
    print(
        "※ 기존 청년주거환경_정책통합분석.csv는 "
        "변경하지 않았습니다."
    )


# =========================================================
# 실행
# =========================================================

if __name__ == "__main__":

    main()